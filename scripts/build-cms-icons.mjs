// Builds the icon set editors can pick in the dashboard: resources/js/components/cmsIcons.ts (site bundle)
// and resources/icons/cms-icons.json (SVG previews for the dashboard picker). Run: node scripts/build-cms-icons.mjs
import { writeFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as lucide from 'lucide-react'

const NAMES = [
  'Award', 'BadgeCheck', 'Banknote', 'BarChart3', 'Boxes', 'Briefcase', 'Building', 'Building2', 'Calculator', 'CalendarCheck',
  'Camera', 'Car', 'ClipboardCheck', 'Clock', 'Cog', 'Coins', 'Compass', 'Cpu', 'Factory', 'FileCheck2', 'FileSignature', 'FileText',
  'Flag', 'Fuel', 'Gavel', 'Globe2', 'GraduationCap', 'Hammer', 'Handshake', 'HardHat', 'HeartPulse', 'Hotel', 'Key', 'Landmark',
  'Laptop', 'Layers', 'Leaf', 'Lightbulb', 'LineChart', 'ListChecks', 'Lock', 'Mail', 'Map', 'MapPin', 'MapPinned', 'MessageCircle',
  'MonitorCheck', 'Mountain', 'Package', 'Palmtree', 'Phone', 'PieChart', 'Pickaxe', 'PiggyBank', 'Plane', 'Receipt', 'Rocket',
  'Scale', 'Server', 'Shapes', 'ShieldCheck', 'Ship', 'ShoppingBag', 'Smartphone', 'Sparkles', 'Sprout', 'Star', 'Stethoscope',
  'Store', 'Sun', 'Sunrise', 'Target', 'Timer', 'Tractor', 'Train', 'TrendingUp', 'Truck', 'UserCheck', 'Users', 'UtensilsCrossed',
  'Wallet', 'Warehouse', 'Waves', 'Wifi', 'Workflow', 'Wrench', 'Zap',
]

const missing = NAMES.filter(n => !lucide[n])
if (missing.length) throw new Error('Unknown lucide icons: ' + missing.join(', '))

const svgs = Object.fromEntries(NAMES.map(n => [n, renderToStaticMarkup(createElement(lucide[n], { size: 22, strokeWidth: 1.6 }))]))
writeFileSync('resources/icons/cms-icons.json', JSON.stringify(svgs, null, 1) + '\n')
writeFileSync('resources/js/components/cmsIcons.ts', `// Generated by scripts/build-cms-icons.mjs; edit the list there.
import { ${NAMES.join(', ')}, type LucideIcon } from 'lucide-react'

/** Icons the CMS may reference by name (same list as the dashboard icon picker). */
export const CMS_ICONS: Record<string, LucideIcon> = {
  ${NAMES.join(', ')},
}
`)
console.log(NAMES.length, 'icons')
